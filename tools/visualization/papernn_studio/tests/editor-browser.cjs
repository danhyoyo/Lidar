/* Full editor workflow: run with playwright-core and installed Chromium. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const {chromium}=require('playwright-core');
const viewer=path.resolve(__dirname,'..');
(async()=>{
    const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
    try{
        const page=await browser.newPage({viewport:{width:1700,height:1100},acceptDownloads:true});
        page.setDefaultTimeout(12000);
        const errors=[],requests=[];page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(/^https?:/.test(r.url()))requests.push(r.url());});
        await page.goto(pathToFileURL(path.join(viewer,'Backbone.html')).href);
        await page.waitForSelector('[data-node="stage2"]');
        assert.equal(await page.locator('#presentation').inputValue(),'reference');
        assert.equal(await page.locator('#error').isVisible(),false);
        assert.equal(await page.locator('.tensor-node').count(),14);
        assert.equal(await page.locator('[data-group="backbone"]').count(),1);
        await page.locator('[data-node="stage2"]').click();
        await page.locator('#node-label').fill('Custom encoder');
        await page.locator('#node-shape-0').fill('64');
        await page.locator('#node-fill').fill('#aaccee');
        await page.locator('#node-form summary').filter({hasText:'Thông số block'}).click();
        await page.locator('#node-repeat').fill('5');
        await page.locator('#node-apply').click();
        assert.match(await page.locator('[data-node="stage2"]').textContent(),/Custom encoder/);
        assert.match(await page.locator('[data-node="stage2"]').textContent(),/64 × 200 × 176/);
        assert.match(await page.locator('[data-node="stage2"]').textContent(),/NeXt × 5/);
        assert.equal(await page.locator('#shape-mode').innerText(),'Shapes: nhập thủ công');
        assert.equal(await page.locator('#error').isVisible(),false);
        await page.locator('#undo').click();
        assert.match(await page.locator('[data-node="stage2"]').textContent(),/48 × 200 × 176/);
        await page.locator('#redo').click();
        await page.locator('[data-node="stage2"]').click();
        const originalX=Number(await page.locator('#node-x').inputValue());
        const originalY=Number(await page.locator('#node-y').inputValue());
        await page.locator('#edit-mode').click();
        const block=await page.locator('[data-node="stage2"] > rect').first().boundingBox();
        await page.mouse.move(block.x+block.width/2,block.y+block.height/2);
        await page.mouse.down();await page.mouse.move(block.x+block.width/2+52,block.y+block.height/2+20,{steps:6});await page.mouse.up();
        assert.ok(Number(await page.locator('#node-x').inputValue())>originalX+20);
        assert.ok(Number(await page.locator('#node-y').inputValue())>originalY+5);
        const width=Number(await page.locator('#node-width').inputValue());
        const corner=await page.locator('[data-node="stage2"] [data-resize]').boundingBox();
        await page.mouse.move(corner.x+5,corner.y+5);await page.mouse.down();await page.mouse.move(corner.x+35,corner.y+20,{steps:5});await page.mouse.up();
        assert.ok(Number(await page.locator('#node-width').inputValue())>width+10);
        // Add any block, link it through the canvas, edit ports and a manual waypoint.
        await page.locator('#block-library').selectOption('conv');await page.locator('#add-node').click();
        assert.equal(await page.locator('.tensor-node').count(),15);
        const id=await page.locator('.tensor-node.selected').getAttribute('data-node');
        await page.locator('#node-label').fill('My projection');await page.locator('#node-apply').click();
        await page.locator('#connect-mode').click();
        await page.locator('[data-node="output"]').click();await page.locator(`[data-node="${id}"]`).click();
        const edge=page.locator(`.edge-node[data-source="output"][data-target="${id}"]`);
        assert.equal(await edge.count(),1);
        await edge.locator('.edge-hit').click({force:true});
        await page.locator('#edge-label').fill('custom branch');
        await page.locator('#edge-source-port').selectOption('right');
        await page.locator('#edge-target-port').selectOption('left');
        await page.locator('#edge-bend-x').fill('1000');await page.locator('#edge-bend-y').fill('300');
        await page.locator('#edge-apply').click();
        assert.match(await edge.locator('.edge-line').getAttribute('d'),/1000 300/);
        // Group commands and cascade deletion remain undoable.
        await page.locator('#tab-groups').click();
        await page.locator('#add-group').click();await page.locator('#group-label').fill('Custom region');
        await page.locator('#group-none').click();await page.locator(`#group-nodes input[value="${id}"]`).check();await page.locator('#group-apply').click();
        assert.match(await page.locator('#canvas').textContent(),/Custom region/);
        await page.locator(`[data-node="${id}"]`).click();await page.locator('#remove-node').click();
        assert.equal(await page.locator(`[data-node="${id}"]`).count(),0);assert.equal(await edge.count(),0);
        await page.locator('#undo').click();assert.equal(await page.locator(`[data-node="${id}"]`).count(),1);assert.equal(await edge.count(),1);
        await page.locator('#tab-save').click();
        const downloading=page.waitForEvent('download');await page.locator('#download-json').click();
        const download=await downloading,stream=await download.createReadStream(),chunks=[];
        for await(const chunk of stream)chunks.push(chunk);
        const saved=JSON.parse(Buffer.concat(chunks).toString());
        assert.equal(saved.views.overview.nodes.find(n=>n.id==='stage2').shape[0],64);
        assert.equal(saved.views.overview.edges.find(e=>e.target===id).target_port,'left');
        const downloadingSVG=page.waitForEvent('download');await page.locator('#download').click();
        const svgDownload=await downloadingSVG,svgStream=await svgDownload.createReadStream(),svgChunks=[];
        for await(const chunk of svgStream)svgChunks.push(chunk);
        const svg=Buffer.concat(svgChunks).toString();assert.match(svg,/My projection/);assert.match(svg,/custom branch/);
        assert.match(svg,/viewBox="0 0/);assert.doesNotMatch(svg,/class="tensor-node[^\"]*selected/);
        // Reload preserves edited document. A blank drawing accepts arbitrary blocks.
        await page.reload();await page.waitForSelector(`[data-node="${id}"]`);
        assert.match(await page.locator('[data-node="stage2"]').textContent(),/64 × 200 × 176/);
        await page.locator('#tab-save').click();await page.locator('#new-drawing').click();
        assert.equal(await page.locator('.tensor-node').count(),1);
        await page.locator('#tab-blocks').click();await page.locator('#block-library').selectOption('block');await page.locator('#add-node').click();
        assert.equal(await page.locator('.tensor-node').count(),2);
        await page.locator('#import-file').setInputFiles({name:'edited.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(saved))});
        await page.waitForSelector(`[data-node="${id}"]`);assert.match(await page.locator('#canvas').textContent(),/Custom encoder/);
        const invalid=JSON.parse(JSON.stringify(saved));invalid.views.overview.nodes[0].layout.fill='url(javascript:alert(1))';
        await page.locator('#import-file').setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(invalid))});
        await page.waitForFunction(()=>!document.getElementById('error').hidden);
        assert.equal(await page.locator('.tensor-node').count(),15);
        // Restore a clean config-derived overview for screenshot and mobile check.
        await page.locator('#tab-save').click();
        await page.locator('#reset-preset').click();
        assert.equal(await page.locator('#error').isVisible(),false);assert.equal(await page.locator('.tensor-node').count(),14);
        await page.locator('#tab-setup').click();if(process.argv[2])await page.screenshot({path:process.argv[2],fullPage:true});
        await page.setViewportSize({width:540,height:950});assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
        assert.deepEqual(errors,[]);assert.deepEqual(requests,[]);
        console.log('Editor browser checks passed: properties/repeat, drag/resize, connect/routes, groups, delete/undo, JSON/SVG export, persistence, new drawing, import validation and mobile layout.');
    }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
