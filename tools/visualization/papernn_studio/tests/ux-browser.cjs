        await page.locator('#tab-groups').click();await page.locator('#add-group').click();
        assert.equal(await page.locator(`#group-nodes input[value="${id}"]`).isChecked(),true);
        const group=await page.locator('#group-select').inputValue();
        assert.equal(await page.locator(`[data-group="${group}"]`).count(),1,'A group made from selection should be visible immediately');
        await page.locator('#group-label').fill('Touch-friendly group');
        await page.locator('#group-nodes input[value="stage2"]').check();
        await page.locator('#group-apply').click();
        assert.match(await page.locator('#canvas').textContent(),/Touch-friendly group/);
        assert.match(await page.locator('#group-count').textContent(),/2/);
        // Both panels may contain pending edits. Applying must preserve both drafts.
        await page.locator('#group-label').fill('');
        await page.locator('#tab-blocks').click();
        await page.locator('#node-label').fill('Concurrent node draft');
        await page.locator('#node-apply').click();
        const unchanged=await page.evaluate(()=>JSON.parse(localStorage.getItem('nn-svg-backbone-editor-v1')).document);
        assert.notEqual(unchanged.views.overview.nodes.find(n=>n.id===id).label,'Concurrent node draft','Invalid pending group must prevent partial apply');
        await page.locator('#group-label').fill('Concurrent group draft');await page.locator('#group-apply').click();
        const stored=await page.evaluate(()=>JSON.parse(localStorage.getItem('nn-svg-backbone-editor-v1')).document);
        assert.equal(stored.views.overview.groups.find(g=>g.id===group).label,'Concurrent group draft');
        assert.equal(stored.views.overview.nodes.find(n=>n.id===id).label,'Concurrent node draft');
        assert.ok(stored.views.overview.groups.find(g=>g.id==='backbone').node_ids.includes('stage2'));
        await page.locator('[data-node="stage2"]').click();
        await page.locator('#node-font-slider').fill('19.5');await page.locator('#node-apply').click();
        const styled=await page.evaluate(()=>JSON.parse(localStorage.getItem('nn-svg-backbone-editor-v1')).document);
        assert.equal(styled.views.overview.nodes.find(n=>n.id==='stage2').layout.font_size,19.5);
        assert.equal(styled.views.overview.groups.filter(g=>g.node_ids.includes('stage2')).length,2,'Styling must preserve membership in multiple groups');
