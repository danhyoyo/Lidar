        await page.locator('#tab-setup').click();
        await page.locator('#spacing').fill('1.35');
        assert.equal(await page.locator('#canvas svg').getAttribute('viewBox'),zoom,'A slider must preserve pan/zoom');
        assert.equal(await page.locator('#node-label').inputValue(),'Draft survives sliders','A slider must preserve uncommitted fields');
        assert.equal(await page.locator('#spacing-number').inputValue(),'1.35');
        assert.equal(await page.locator('#spacing').getAttribute('aria-valuetext'),'1.35 lần');
        await page.locator('#spacing-number').fill('1.05');await page.locator('#spacing-number').press('Enter');
        assert.equal(await page.locator('#spacing').inputValue(),'1.05');
        await page.locator('#reset-3d').click();assert.equal(await page.locator('#spacing').inputValue(),'1');
        await page.locator('#presentation').selectOption('reference');
        assert.match(await page.locator('[data-node="stage2"]').textContent(),/Draft survives sliders/);
        await page.locator('[data-node="stage2"]').click();
        await page.locator('#node-label').fill('Applied when switching');
        await page.locator('[data-node="stage3"]').click();
        assert.match(await page.locator('[data-node="stage2"]').textContent(),/Applied when switching/);
        await page.locator('#node-shape-0').fill('0');
        await page.locator('[data-node="stage4"]').click();
        assert.equal(await page.locator('#node-shape-0').inputValue(),'0','Invalid fields must remain available to correct');
        assert.equal(await page.locator('.tensor-node.selected').getAttribute('data-node'),'stage3');
        await page.locator('#node-cancel').click();
        const details=page.locator('#node-form details').filter({has:page.locator('#node-kernel')});
        await details.locator('summary').click();await page.locator('#node-kernel').fill('0');await details.locator('summary').click();
        await page.locator('#node-apply').click();assert.equal(await details.getAttribute('open'),'');
        assert.equal(await page.locator('#node-kernel').evaluate(n=>n===document.activeElement),true);
        await page.locator('#node-cancel').click();
        await page.locator('#add-block').click();await page.locator('#block-library').selectOption('conv');await page.locator('#add-node').click();
